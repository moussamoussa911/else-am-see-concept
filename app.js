const bookingState = {
  date: "",
  dateLabel: "",
  moment: "breakfast",
  time: "09:00",
  party: 2,
  area: "terrace",
  table: ""
};

function localeCode() {
  return lang === "nl" ? "nl-NL" : lang === "en" ? "en-GB" : "de-DE";
}

function renderDates() {
  const strip = document.getElementById("date-strip");
  if (!strip) return;
  const dates = Array.from({ length: 7 }, (_, index) => {
    const date = new Date();
    date.setHours(12, 0, 0, 0);
    date.setDate(date.getDate() + index + 1);
    return date;
  });
  if (!bookingState.date) {
    bookingState.date = dates[0].toISOString().slice(0, 10);
  }
  strip.innerHTML = dates.map(date => {
    const iso = date.toISOString().slice(0, 10);
    const weekday = new Intl.DateTimeFormat(localeCode(), { weekday: "short" }).format(date).replace(".", "");
    return `<button class="date-card ${iso === bookingState.date ? "is-active" : ""}" type="button" data-date="${iso}">
      <span>${weekday}</span><strong>${date.getDate()}</strong>
    </button>`;
  }).join("");
  strip.querySelectorAll("[data-date]").forEach(button => button.addEventListener("click", () => {
    bookingState.date = button.dataset.date;
    strip.querySelectorAll("button").forEach(item => item.classList.toggle("is-active", item === button));
    updateBookingSummary();
  }));
  updateBookingSummary();
}

function renderTimes(start, end) {
  const grid = document.getElementById("time-grid");
  if (!grid) return;
  const result = [];
  const [startH, startM] = start.split(":").map(Number);
  const [endH, endM] = end.split(":").map(Number);
  for (let minutes = startH * 60 + startM; minutes <= endH * 60 + endM; minutes += 30) {
    result.push(`${String(Math.floor(minutes / 60)).padStart(2, "0")}:${String(minutes % 60).padStart(2, "0")}`);
  }
  if (!result.includes(bookingState.time)) bookingState.time = result[0];
  grid.innerHTML = result.map(time => `<button class="time-chip ${time === bookingState.time ? "is-active" : ""}" type="button" data-time="${time}">${time}</button>`).join("");
  grid.querySelectorAll("[data-time]").forEach(button => button.addEventListener("click", () => {
    bookingState.time = button.dataset.time;
    grid.querySelectorAll("button").forEach(item => item.classList.toggle("is-active", item === button));
    updateBookingSummary();
  }));
  updateBookingSummary();
}

function updateBookingSummary() {
  const dateNode = document.getElementById("summary-date");
  if (!dateNode) return;
  const date = bookingState.date ? new Date(`${bookingState.date}T12:00:00`) : null;
  bookingState.dateLabel = date ? new Intl.DateTimeFormat(localeCode(), { weekday: "short", day: "2-digit", month: "2-digit" }).format(date) : "—";
  dateNode.textContent = bookingState.dateLabel;
  document.getElementById("summary-time").textContent = bookingState.time || "—";
  document.getElementById("summary-guests").textContent = bookingState.party;
  document.getElementById("summary-table").textContent = bookingState.table || "—";
  const areaKey = bookingState.area === "terrace" ? "areaTerrace" : bookingState.area === "inside" ? "areaInside" : "areaBeach";
  document.querySelector(".summary-visual span").textContent = t(areaKey);
}

function setBookingStep(step) {
  document.querySelectorAll("[data-step-panel]").forEach(panel => panel.classList.toggle("is-active", Number(panel.dataset.stepPanel) === step));
  document.querySelectorAll("[data-book-step]").forEach(button => {
    const number = Number(button.dataset.bookStep);
    button.classList.toggle("is-active", number === step);
    button.classList.toggle("is-done", number < step);
  });
  document.getElementById("booking-panel")?.scrollIntoView({ behavior: "smooth", block: "start" });
}

function initBooking() {
  renderDates();
  renderTimes("09:00", "11:30");
  document.querySelectorAll("[data-moment]").forEach(button => button.addEventListener("click", () => {
    document.querySelectorAll("[data-moment]").forEach(item => item.classList.toggle("is-active", item === button));
    bookingState.moment = button.dataset.moment;
    renderTimes(button.dataset.start, button.dataset.end);
  }));
  document.querySelectorAll("[data-party]").forEach(button => button.addEventListener("click", () => {
    bookingState.party = Math.max(1, Math.min(20, bookingState.party + Number(button.dataset.party)));
    document.getElementById("party-count").textContent = bookingState.party;
    updateBookingSummary();
  }));
  document.querySelectorAll("[data-area]").forEach(button => button.addEventListener("click", () => {
    document.querySelectorAll("[data-area]").forEach(item => item.classList.toggle("is-active", item === button));
    bookingState.area = button.dataset.area;
    bookingState.table = "";
    document.querySelectorAll("[data-table]").forEach(table => table.classList.remove("is-selected"));
    updateBookingSummary();
  }));
  document.querySelectorAll("[data-table]:not(:disabled)").forEach(table => table.addEventListener("click", () => {
    bookingState.table = table.dataset.table;
    document.querySelectorAll("[data-table]").forEach(item => item.classList.toggle("is-selected", item === table));
    updateBookingSummary();
  }));
  document.querySelectorAll(".next-step").forEach(button => button.addEventListener("click", () => {
    const active = Number(document.querySelector(".booking-step.is-active").dataset.stepPanel);
    if (active === 2 && !bookingState.table) {
      showToast(t("chooseTableFirst"));
      return;
    }
    setBookingStep(Math.min(4, active + 1));
  }));
  document.querySelectorAll(".back-step").forEach(button => button.addEventListener("click", () => {
    const active = Number(document.querySelector(".booking-step.is-active").dataset.stepPanel);
    setBookingStep(Math.max(1, active - 1));
  }));
  document.getElementById("booking-form")?.addEventListener("submit", event => {
    event.preventDefault();
    const ticket = document.getElementById("success-ticket");
    ticket.innerHTML = `
      <div><small>${t("dateShort")}</small><strong>${bookingState.dateLabel}</strong></div>
      <div><small>${t("timeShort")}</small><strong>${bookingState.time}</strong></div>
      <div><small>${t("guestsShort")}</small><strong>${bookingState.party}</strong></div>
      <div><small>${t("tableShort")}</small><strong>${bookingState.table}</strong></div>`;
    document.getElementById("summary-status").textContent = t("completed");
    setBookingStep(4);
  });
}

