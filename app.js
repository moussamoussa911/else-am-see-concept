function cartCount() {
  return Object.values(cart).reduce((sum, quantity) => sum + quantity, 0);
}

function saveCart() {
  localStorage.setItem("else-cart", JSON.stringify(cart));
  localStorage.setItem("else-cart-people", String(cartPeople));
}

function addToCart(id) {
  cart[id] = (cart[id] || 0) + 1;
  saveCart();
  renderCart();
  showToast(t("added"));
}

function adjustCart(id, delta) {
  cart[id] = (cart[id] || 0) + delta;
  if (cart[id] <= 0) delete cart[id];
  saveCart();
  renderCart();
}

function removeFromCart(id) {
  delete cart[id];
  saveCart();
  renderCart();
}

